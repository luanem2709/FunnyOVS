const TABLES: Record<Lang, Record<string, string>> = { vi: MESSAGES_VI, en: MESSAGES_EN };

/**
 * Dịch một khoá. Giá trị biến dạng "$t:khoá.khác" được dịch tiếp (dùng cho phần chèn cũng cần dịch,
 * ví dụ hành động "đọc"/"read" trong câu xin quyền).
 */
export function msg(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = TABLES[lang]?.[key] ?? TABLES.vi[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      const value = typeof v === "string" && v.startsWith("$t:") ? msg(lang, v.slice(3)) : String(v);
      s = s.split(`{${k}}`).join(value);
    }
  }
  return s;
}

export function normalizeLang(v: unknown): Lang {
  return v === "en" ? "en" : "vi";
}
